// ============================================================
// Firebase Admin — Server-side Firebase initialization
// ============================================================
// Initializes the Firebase Admin SDK using the service account
// credentials. Used to verify Firebase ID tokens sent by the
// frontend after phone authentication.
//
// The service account key file must exist at:
//   backend/firebase-service-account.json
//
// This file is in .gitignore — NEVER commit it to source control.
// ============================================================

import * as admin from 'firebase-admin';
import path from 'path';
import { logger } from '../utils/logger';

// ── Initialize Firebase Admin ─────────────────────────────────

const serviceAccountPath = path.resolve(__dirname, '../../firebase-service-account.json');

let firebaseApp: admin.app.App;

try {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const serviceAccount = require(serviceAccountPath);

  firebaseApp = admin.initializeApp({
    credential: admin.credential.cert(serviceAccount),
  });

  logger.info('Firebase Admin SDK initialized', {
    projectId: serviceAccount.project_id,
  });
} catch (error: any) {
  logger.error('Failed to initialize Firebase Admin SDK', {
    message: error.message,
    hint: 'Ensure firebase-service-account.json exists in the backend/ folder',
  });
  // Don't crash the server — Firebase endpoints will return appropriate errors
}

// ── Token Verification ────────────────────────────────────────

/**
 * Verify a Firebase ID token and return the decoded claims.
 *
 * The ID token is generated by the Firebase client SDK after
 * successful phone authentication. It contains:
 *   - uid:          Firebase user ID
 *   - phone_number: The verified phone number (e.g., "+919876543210")
 *   - auth_time:    When the user authenticated
 *
 * @throws Error if token is invalid, expired, or revoked
 */
export async function verifyFirebaseIdToken(
  idToken: string,
): Promise<admin.auth.DecodedIdToken> {
  if (!firebaseApp) {
    throw new Error('Firebase Admin SDK not initialized');
  }

  return admin.auth().verifyIdToken(idToken, /* checkRevoked */ true);
}

export { firebaseApp };
